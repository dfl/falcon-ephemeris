export function deltaTSeconds(jdUt) {
  const year = 2000 + (jdUt - 2451545.0) / 365.25;
  const n = DELTA_T.length, last = DELTA_T_YEAR0 + n - 1;
  if (year <= DELTA_T_YEAR0) return DELTA_T[0] + (DELTA_T[1] - DELTA_T[0]) * (year - DELTA_T_YEAR0);
  if (year >= last) return DELTA_T[n - 1] + (DELTA_T[n - 1] - DELTA_T[n - 2]) * (year - last);
  const i = Math.floor(year) - DELTA_T_YEAR0;
  return DELTA_T[i] + (DELTA_T[i + 1] - DELTA_T[i]) * (year - Math.floor(year));
}
